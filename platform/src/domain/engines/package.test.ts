import { describe, it, expect } from 'vitest'
import { closeTo, pence } from '../../test/helpers'
import { DEFAULT_ASSUMPTIONS as A, facilityById } from '../reference/assumptions'
import { buyerPackage, sellerPackage, holdingView, confirmedStorageMonths, loadsFor } from './package'

const TILB = facilityById('HUB-TILB')
const BARK = facilityById('HUB-BARK')
const PARK = facilityById('HUB-PARK')
const TH01 = { family: 'steel_section' as const, pieces: 48, units: 24.156, massT: 24.156, baselineQty: 23.18976 }

describe('B8 package costs (F8), the TH-01 allocation', () => {
  it('B8.1 estimate at guide 770, Tilbury, 16 months', () => {
    const r = buyerPackage({ ...TH01, pricePerUnit: 770, testing: true, route: 'hub', facility: TILB, kmToProject: 31, storageMonths: 16 }, A)
    pence(r.material, 18600.12)
    pence(r.testing, 1800)
    pence(r.storage, 1352.74)
    pence(r.handlingOut, 217.4)
    pence(r.outbound, 235.8)
    pence(r.total, 22206.06)
    pence(r.costNew, 23189.76)
    pence(r.saving, 983.7)
    closeTo(r.savingPercent * 100, 4.242, 3)
    closeTo(r.breakEvenMonths!, 27.635, 3)
    expect(loadsFor(24.156, A)).toBe(1)
  })
  it('B8.2 estimate at 740, Tilbury, 16 months', () => {
    const r = buyerPackage({ ...TH01, pricePerUnit: 740, testing: true, route: 'hub', facility: TILB, kmToProject: 31, storageMonths: 16 }, A)
    pence(r.material, 17875.44)
    pence(r.total, 21481.38)
    pence(r.saving, 1708.38)
    closeTo(r.savingPercent * 100, 7.367, 3)
    closeTo(r.breakEvenMonths!, 36.207, 3)
  })
  it('B8.3 confirmed at 740, Tilbury, 13 months', () => {
    expect(confirmedStorageMonths('2027-03-15', '2028-04-03', '2026-10-07')).toBe(13)
    const r = buyerPackage({ ...TH01, pricePerUnit: 740, testing: true, route: 'hub', facility: TILB, kmToProject: 31, storageMonths: 13 }, A)
    pence(r.storage, 1099.1)
    pence(r.total, 21227.74)
    pence(r.saving, 1962.02)
    closeTo(r.savingPercent * 100, 8.461, 3)
    closeTo(r.breakEvenMonths!, 36.207, 3)
    const s = sellerPackage({ family: 'steel_section', units: 24.156, massT: 24.156, pricePerUnit: 740, route: 'hub', facility: TILB, kmSourceToHub: 38, inStock: null, dealDate: '2026-10-07' }, A)
    pence(s.commission, 1430.04)
    pence(s.inbound, 248.4)
    pence(s.handlingIn, 217.4)
    pence(s.net, 15979.6)
    pence(s.scrapValue, 5314.32)
    pence(s.premium, 2174.04)
    pence(s.upliftVsScrap, 8491.24)
  })
  it('B8.4 confirmed at 740, Barking, 13 months', () => {
    const r = buyerPackage({ ...TH01, pricePerUnit: 740, testing: true, route: 'hub', facility: BARK, kmToProject: 14, storageMonths: 13 }, A)
    pence(r.storage, 1570.14)
    pence(r.handlingOut, 241.56)
    pence(r.outbound, 205.2)
    pence(r.total, 21692.34)
    pence(r.saving, 1497.42)
    closeTo(r.savingPercent * 100, 6.457, 3)
    closeTo(r.breakEvenMonths!, 25.398, 3)
    const s = sellerPackage({ family: 'steel_section', units: 24.156, massT: 24.156, pricePerUnit: 740, route: 'hub', facility: BARK, kmSourceToHub: 18, inStock: null, dealDate: '2026-10-07' }, A)
    pence(s.inbound, 212.4)
    pence(s.handlingIn, 241.56)
    pence(s.net, 15991.44)
    pence(s.upliftVsScrap, 8503.08)
  })
  it('B8.5 confirmed at 740, direct', () => {
    const r = buyerPackage({ ...TH01, pricePerUnit: 740, testing: true, route: 'direct', facility: null, kmToProject: 9, storageMonths: 0 }, A)
    pence(r.storage, 0)
    pence(r.handlingOut, 0)
    pence(r.outbound, 196.2)
    pence(r.total, 19871.64)
    pence(r.saving, 3318.12)
    closeTo(r.savingPercent * 100, 14.309, 3)
    expect(r.breakEvenMonths).toBeNull()
    const s = sellerPackage({ family: 'steel_section', units: 24.156, massT: 24.156, pricePerUnit: 740, route: 'direct', facility: null, kmSourceToHub: 0, inStock: null, dealDate: '2026-10-07' }, A)
    pence(s.commission, 1430.04)
    pence(s.inbound, 0)
    pence(s.net, 16445.4)
    pence(s.upliftVsScrap, 8957.04)
  })
  it('B8.6 facility comparison at the guide price, 16 months', () => {
    const t = buyerPackage({ ...TH01, pricePerUnit: 770, testing: true, route: 'hub', facility: TILB, kmToProject: 31, storageMonths: 16 }, A)
    const b = buyerPackage({ ...TH01, pricePerUnit: 770, testing: true, route: 'hub', facility: BARK, kmToProject: 14, storageMonths: 16 }, A)
    const p = buyerPackage({ ...TH01, pricePerUnit: 770, testing: true, route: 'hub', facility: PARK, kmToProject: 24, storageMonths: 16 }, A)
    pence(t.total, 22206.06)
    pence(t.saving, 983.7)
    pence(b.total, 22779.36)
    pence(b.saving, 410.4)
    pence(p.total, 26324.13)
    pence(p.saving, -3134.37)
    closeTo(-p.savingPercent * 100, 13.516, 3)
  })
  it("B8.7 owner's holding view for TH-01 via Barking", () => {
    const h = holdingView({ family: 'steel_section', units: 24.156, massT: 24.156, pricePerUnit: 770, facility: BARK, kmSourceToHub: 18, inStock: null, dealDate: '2026-10-07' }, A)
    pence(h.material, 18600.12)
    pence(h.commission, 1488.01)
    pence(h.inbound, 212.4)
    pence(h.handlingIn, 241.56)
    pence(h.net, 16658.15)
    pence(h.upliftVsScrap, 9169.79)
    closeTo(h.holdMonths!, 75.921, 3)
  })
  it("B8.8 owner's holding view for TH-11 via Park Royal", () => {
    const h = holdingView({ family: 'raised_floor', units: 3000, massT: 36, pricePerUnit: 3.6, facility: PARK, kmSourceToHub: 14, inStock: null, dealDate: '2026-10-07' }, A)
    pence(h.material, 10800)
    pence(h.commission, 864)
    pence(h.inbound, 410.4)
    pence(h.handlingIn, 432)
    pence(h.net, 9093.6)
    pence(h.scrapValue, 0)
    pence(h.premium, 3600)
    pence(h.upliftVsScrap, 5493.6)
    closeTo(h.holdMonths!, 10.9, 3)
  })
  it('B8.9 seller storage for stock already in a hub (OS-11)', () => {
    const s = sellerPackage({ family: 'steel_section', units: 9.6624, massT: 9.6624, pricePerUnit: 855, route: 'hub', facility: BARK, kmSourceToHub: 0, inStock: { since: '2026-09-01' }, dealDate: '2026-10-07' }, A)
    expect(s.sellerStorageMonths).toBe(2)
    pence(s.sellerStorage, 96.62)
    pence(s.inbound, 0)
    pence(s.handlingIn, 0)
  })
  it('B8.10 a negative case: OS-11 allocation of 4 pieces at Barking', () => {
    const r = buyerPackage({ family: 'steel_section', pieces: 4, units: 2.4156, massT: 2.4156, baselineQty: 1.93248, pricePerUnit: 855, testing: false, route: 'hub', facility: BARK, kmToProject: 14, storageMonths: 19 }, A)
    pence(r.material, 2065.34)
    pence(r.storage, 229.48)
    pence(r.handlingOut, 24.16)
    pence(r.outbound, 205.2)
    pence(r.total, 2524.18)
    pence(r.costNew, 1932.48)
    pence(r.saving, -591.7)
    closeTo(-r.savingPercent * 100, 30.619, 3)
  })
})
